/**
 * System Design Module 6: Distributed Object Storage Service (S3-Lite)
 * 
 * Core System Design Principles:
 * 1. Metadata vs Chunk Separation:
 *    File metadata (filename, size, MIME type, chunk manifest, checksum) is stored
 *    in an indexed catalog, completely isolated from raw binary chunk storage.
 * 2. Fixed-Size Chunking & Content-Addressable Storage (CAS):
 *    Files are split into discrete chunks (e.g. 64KB - 256KB).
 *    Each chunk's identifier is its SHA-256 hash. Identical chunks across
 *    different files automatically deduplicate.
 * 3. Replication Factor & Placement Ring (RF = 2):
 *    Every chunk is placed on multiple distinct storage nodes (Node A, Node B, Node C).
 * 4. Fault Tolerance & Graceful Degradation:
 *    If Node A goes down (hardware failure / network partition), read queries
 *    automatically fail over to surviving replica Node B or Node C.
 * 5. Multipart Upload Lifecycle:
 *    Simulates AWS S3 `InitiateMultipartUpload`, `UploadPart`, and `CompleteMultipartUpload`.
 */

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

class ObjectStorageService {
  constructor() {
    this.baseDir = process.env.STORAGE_DATA_DIR || path.join(__dirname, '..', 'data', 'storage_nodes');
    this.nodes = ['node_a', 'node_b', 'node_c'];
    
    // Node status: allows user to simulate hardware crash / partition
    this.nodeHealth = {
      node_a: true,
      node_b: true,
      node_c: true
    };

    // Metadata Catalog: fileId -> fileMetadata
    this.metadataCatalog = new Map();

    // Active Multipart Upload Sessions: uploadId -> sessionObject
    this.activeUploads = new Map();

    // Telemetry metrics
    this.metrics = {
      totalFilesStored: 0,
      totalBytesStored: 0,
      totalChunksCreated: 0,
      deduplicatedChunksAvoided: 0,
      failoverReadsHandled: 0
    };

    this.ensureNodeDirectories();
    this.seedSampleFiles();
  }

  ensureNodeDirectories() {
    this.nodes.forEach(node => {
      const nodeDir = path.join(this.baseDir, node);
      if (!fs.existsSync(nodeDir)) {
        fs.mkdirSync(nodeDir, { recursive: true });
      }
    });
  }

  seedSampleFiles() {
    // Seed a sample architecture diagram document
    const sampleText = `SYSTEM DESIGN LAB ARCHITECTURE SPECIFICATION\n` +
      `=============================================\n` +
      `Module 1: Collaborative Canvas (WebSockets & Vector Clock Sync)\n` +
      `Module 2: Feature Flags (In-memory evaluations & SSE sync)\n` +
      `Module 3: Delayed Job Scheduler (Idempotency & DLQ)\n` +
      `Module 4: API Rate Limiter (Token Bucket & Sliding Window)\n` +
      `Module 5: Activity Feed (Fan-out on Write vs Read)\n` +
      `Module 6: Chunked Distributed Storage (Replication Factor 2)\n` +
      `Generated by SysLab Engine.\n`.repeat(5);

    const buf = Buffer.from(sampleText, 'utf-8');
    this.storeFileDirect('syslab-architecture-blueprint.txt', 'text/plain', buf, 128); // 128-byte chunks for demo
  }

  setNodeStatus(nodeId, isOnline) {
    if (this.nodeHealth.hasOwnProperty(nodeId)) {
      this.nodeHealth[nodeId] = Boolean(isOnline);
      return { node: nodeId, status: this.nodeHealth[nodeId] ? 'ONLINE' : 'OFFLINE' };
    }
    return null;
  }

  /**
   * S3 API 1: Initiate Multipart Upload
   */
  initiateMultipartUpload(filename, totalSize, mimeType = 'application/octet-stream', chunkSize = 64 * 1024) {
    const uploadId = `upload-${Date.now()}-${Math.random().toString(36).substring(2, 7)}`;
    const session = {
      uploadId,
      filename,
      totalSize: Number(totalSize),
      mimeType,
      chunkSize: Math.max(64, Number(chunkSize)),
      chunks: new Map(), // partIndex -> { chunkHash, size, nodes: [] }
      createdAt: Date.now()
    };
    this.activeUploads.set(uploadId, session);
    return { uploadId, chunkSize: session.chunkSize };
  }

  /**
   * S3 API 2: Upload Part
   */
  uploadPart(uploadId, partIndex, chunkBuffer) {
    const session = this.activeUploads.get(uploadId);
    if (!session) {
      throw new Error(`Upload session '${uploadId}' not found or expired.`);
    }

    const hash = crypto.createHash('sha256').update(chunkBuffer).digest('hex');
    const assignedNodes = this.selectReplicaNodes(hash);

    // Save chunk on assigned replica nodes
    let storedCopies = 0;
    assignedNodes.forEach(node => {
      const chunkFilePath = path.join(this.baseDir, node, `${hash}.chunk`);
      if (!fs.existsSync(chunkFilePath)) {
        fs.writeFileSync(chunkFilePath, chunkBuffer);
      } else {
        this.metrics.deduplicatedChunksAvoided++;
      }
      storedCopies++;
    });

    const chunkMeta = {
      partIndex: Number(partIndex),
      chunkHash: hash,
      size: chunkBuffer.length,
      assignedNodes
    };

    session.chunks.set(Number(partIndex), chunkMeta);
    this.metrics.totalChunksCreated++;

    return { partIndex, chunkHash: hash, replicaNodes: assignedNodes };
  }

  /**
   * S3 API 3: Complete Multipart Upload
   */
  completeMultipartUpload(uploadId) {
    const session = this.activeUploads.get(uploadId);
    if (!session) {
      throw new Error(`Upload session '${uploadId}' not found.`);
    }

    const fileId = `obj-${crypto.randomBytes(6).toString('hex')}`;
    const sortedParts = Array.from(session.chunks.values()).sort((a, b) => a.partIndex - b.partIndex);

    // Calculate full file SHA-256 ETag from chunk hashes
    const compositeHash = crypto.createHash('sha256')
      .update(sortedParts.map(p => p.chunkHash).join(''))
      .digest('hex');

    const fileMetadata = {
      fileId,
      filename: session.filename,
      size: session.totalSize,
      mimeType: session.mimeType,
      etag: compositeHash,
      totalChunks: sortedParts.length,
      chunkSize: session.chunkSize,
      chunks: sortedParts,
      uploadedAt: Date.now()
    };

    this.metadataCatalog.set(fileId, fileMetadata);
    this.activeUploads.delete(uploadId);

    this.metrics.totalFilesStored = this.metadataCatalog.size;
    this.metrics.totalBytesStored += session.totalSize;

    return fileMetadata;
  }

  /**
   * Helper: Store a file in one direct call (internally chunked)
   */
  storeFileDirect(filename, mimeType, buffer, chunkSize = 128 * 1024) {
    const { uploadId } = this.initiateMultipartUpload(filename, buffer.length, mimeType, chunkSize);
    let offset = 0;
    let partIndex = 0;

    while (offset < buffer.length) {
      const end = Math.min(offset + chunkSize, buffer.length);
      const chunkBuf = buffer.subarray(offset, end);
      this.uploadPart(uploadId, partIndex, chunkBuf);
      offset = end;
      partIndex++;
    }

    return this.completeMultipartUpload(uploadId);
  }

  /**
   * Select 2 replica nodes for a chunk using consistent ring modulo
   */
  selectReplicaNodes(chunkHash) {
    const hashVal = parseInt(chunkHash.substring(0, 4), 16);
    const primaryIndex = hashVal % this.nodes.length;
    const secondaryIndex = (primaryIndex + 1) % this.nodes.length;

    return [this.nodes[primaryIndex], this.nodes[secondaryIndex]];
  }

  /**
   * Retrieve file with automatic failover across surviving replica nodes
   */
  readFile(fileId) {
    const meta = this.metadataCatalog.get(fileId);
    if (!meta) {
      throw new Error(`File '${fileId}' does not exist in metadata store.`);
    }

    const reconstructedBuffers = [];
    const readReport = [];

    for (const chunk of meta.chunks) {
      let chunkData = null;
      let nodeUsed = null;
      let hadFailover = false;

      // Try assigned nodes in order of availability
      for (const node of chunk.assignedNodes) {
        if (this.nodeHealth[node]) {
          const chunkPath = path.join(this.baseDir, node, `${chunk.chunkHash}.chunk`);
          if (fs.existsSync(chunkPath)) {
            chunkData = fs.readFileSync(chunkPath);
            nodeUsed = node;
            break;
          }
        } else {
          hadFailover = true;
          this.metrics.failoverReadsHandled++;
        }
      }

      if (!chunkData) {
        throw new Error(
          `Chunk quorum loss! Chunk ${chunk.chunkHash} is unavailable because all replica nodes [${chunk.assignedNodes.join(', ')}] are OFFLINE.`
        );
      }

      readReport.push({
        partIndex: chunk.partIndex,
        chunkHash: chunk.chunkHash,
        servedByNode: nodeUsed,
        hadFailover
      });

      reconstructedBuffers.push(chunkData);
    }

    return {
      metadata: meta,
      buffer: Buffer.concat(reconstructedBuffers),
      readReport
    };
  }

  getAllFiles() {
    return Array.from(this.metadataCatalog.values()).sort((a, b) => b.uploadedAt - a.uploadedAt);
  }

  getFileMetadata(fileId) {
    return this.metadataCatalog.get(fileId);
  }

  getClusterStatus() {
    // Count chunks stored on each node
    const nodeStats = {};
    this.nodes.forEach(node => {
      const nodeDir = path.join(this.baseDir, node);
      const files = fs.existsSync(nodeDir) ? fs.readdirSync(nodeDir) : [];
      nodeStats[node] = {
        online: this.nodeHealth[node],
        chunkCount: files.length,
        diskPath: nodeDir
      };
    });

    return {
      nodes: nodeStats,
      replicationFactor: 2,
      totalFiles: this.metadataCatalog.size,
      metrics: this.metrics
    };
  }
}

module.exports = new ObjectStorageService();
